#define IL79451A_DISPLAY_ID 0x79450100

bool IL79451AConstractor(DisplayStruct* display) {
    if (display->ID && display->ID != IL79451A_DISPLAY_ID)
        return false;

    DisplayStartupSequence(display, true, true, 20, 10, 100);

    if (!display->ID && (display->ID = DisplayDSIReadID(display, NULL)) != IL79451A_DISPLAY_ID)
        return false;

    display->PixelClock = IL79451A_PIXEL_CLOCK;

    display->HorizontalSyncActive = IL79451A_HSA;
    display->HorizontalBackPorch  = IL79451A_HBP;
    display->HorizontalActive     = IL79451A_HACT;
    display->HorizontalFrontPorch = IL79451A_HFP;

    display->VerticalSyncActive = IL79451A_VSA;
    display->VerticalBackPorch  = IL79451A_VBP;
    display->VerticalActive     = IL79451A_VACT;
    display->VerticalFrontPorch = IL79451A_VFP;

    // DSI Config
    display->ConfigPackets = IL79451AConfigs;
    display->Color         = DisplayColorRGB565;

    DSIStruct* dsi = display->DSIHandle;
    dsi->LaneClock = IL79451A_LANE_CLOCK;
    dsi->Lanes     = DSILanes2;

    dsi->ColorCoding = DSIColorCoding24;

    dsi->IsCommandMode = false;

    return true;
}