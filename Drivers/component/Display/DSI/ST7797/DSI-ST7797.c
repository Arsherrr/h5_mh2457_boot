#define ST7797_DISPLAY_ID 0xFF779700

bool ST7797Constractor(DisplayStruct* display) {
    if (display->ID && display->ID != ST7797_DISPLAY_ID)
        return false;

    DisplayStartupSequence(display, true, true, 20, 20, 120);

    if (!display->ID && (display->ID = DisplayDSIReadID(display, NULL)) != ST7797_DISPLAY_ID)
        return false;

    display->HorizontalSyncActive = ST7797_HSA;
    display->HorizontalBackPorch  = ST7797_HBP;
    display->HorizontalActive     = ST7797_HACT;
    display->HorizontalFrontPorch = ST7797_HFP;

    display->VerticalSyncActive = ST7797_VSA;
    display->VerticalBackPorch  = ST7797_VBP;
    display->VerticalActive     = ST7797_VACT;
    display->VerticalFrontPorch = ST7797_VFP;

    display->PixelClock = 24000;

    // DSI Config
    display->ConfigPackets = ST7797Configs;
    display->Color         = DisplayColorRGB565;

    DSIStruct* dsi = display->DSIHandle;
    dsi->LaneClock = 480000; // 480M
    dsi->Lanes     = DSILanes1;

    dsi->IsCommandMode = false;

    return true;
}
