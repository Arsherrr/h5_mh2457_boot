#define GC9503V_DISPLAY_ID 0x00950400

bool GC9503VConstractor(DisplayStruct* display) {
    if (display->ID && display->ID != GC9503V_DISPLAY_ID)
        return false;

    DisplayStartupSequence(display, true, true, 20, 20, 120);

    if (!display->ID && (display->ID = DisplayDSIReadID(display, NULL)) != GC9503V_DISPLAY_ID)
        return false;

    display->PixelClock = GC9503V_PIXEL_CLOCK;

    display->HorizontalSyncActive = GC9503V_HSA;
    display->HorizontalBackPorch  = GC9503V_HBP;
    display->HorizontalActive     = GC9503V_HACT;
    display->HorizontalFrontPorch = GC9503V_HFP;

    // Insert Dummy Area
    display->HorizontalDummy = GC9503V_HDUM;

    display->VerticalSyncActive = GC9503V_VSA;
    display->VerticalBackPorch  = GC9503V_VBP;
    display->VerticalActive     = GC9503V_VACT;
    display->VerticalFrontPorch = GC9503V_VFP;

    // DSI Config
    display->ConfigPackets = GC9503VConfigs;
    display->Color         = DisplayColorRGB565;

    DSIStruct* dsi     = display->DSIHandle;
    dsi->LaneClock     = GC9503V_LANE_CLOCK;
    dsi->Lanes         = DSILanes2;
    dsi->ColorCoding   = DSIColorCoding16C1;
    dsi->IsCommandMode = false;

    return true;
}