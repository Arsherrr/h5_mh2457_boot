static const DSIPacketStruct ReadSequence[] = {
    MakeDSIPacketRead(2, DCSReadDDBStart),

    MakeDSIPacketEnd(),
};

#define ST7701S_DISPLAY_ID_2 0x88020000
#define ST7701S_DISPLAY_ID_3 0x99030000

bool ST7701SConstractor(DisplayStruct* display) {
    DisplayStartupSequence(display, true, true, 20, 20, 120);

    uint32_t displayID = DisplayDSIReadID(display, ReadSequence);
    if (displayID != ST7701S_DISPLAY_ID_2 && displayID != ST7701S_DISPLAY_ID_3)
        return false;

    display->ID = displayID;

    display->PixelClock = ST7701S_PIXEL_CLOCK;

    display->HorizontalSyncActive = ST7701S_HSA;
    display->HorizontalBackPorch  = ST7701S_HBP;
    display->HorizontalActive     = ST7701S_HACT;
    display->HorizontalFrontPorch = ST7701S_HFP;

    display->VerticalSyncActive = ST7701S_VSA;
    display->VerticalBackPorch  = ST7701S_VBP;
    display->VerticalActive     = ST7701S_VACT;
    display->VerticalFrontPorch = ST7701S_VFP;

    // DSI Config
    display->ConfigPackets = ST7701SConfigs;

    display->Color = DisplayColorRGB565;

    DSIStruct* dsi   = display->DSIHandle;
    dsi->LaneClock   = ST7701S_LANE_CLOCK;
    dsi->Lanes       = DSILanes2;
    dsi->ColorCoding = DSIColorCoding16C1;

    dsi->IsCommandMode = false;
    return true;
}
