#define AXS15260_DISPLAY_ID 0x00015620

bool AXS15260Constractor(DisplayStruct* display) {
    DisplayStartupSequence(display, true, true, 20, 20, 120);

    // mipi read is not supported

    // uint32_t displayID = DisplayDSIReadID(display, ReadSequence);
    // if (displayID != AXS15260_DISPLAY_ID)
    //    return false;

    display->ID         = 0x15620;
    display->PixelClock = AXS15260_PIXEL_CLOCK;

    display->HorizontalSyncActive = AXS15260_HSA;
    display->HorizontalBackPorch  = AXS15260_HBP;
    display->HorizontalActive     = AXS15260_HACT;
    display->HorizontalFrontPorch = AXS15260_HFP;

    display->VerticalSyncActive = AXS15260_VSA;
    display->VerticalBackPorch  = AXS15260_VBP;
    display->VerticalActive     = AXS15260_VACT;
    display->VerticalFrontPorch = AXS15260_VFP;

    // DSI Config
    display->ConfigPackets = AXS15260Configs;

    display->Color = DisplayColorRGB565;

    DSIStruct* dsi   = display->DSIHandle;
    dsi->LaneClock   = AXS15260_LANE_CLOCK;
    dsi->Lanes       = DSILanes2;
    dsi->ColorCoding = DSIColorCoding24;

    dsi->IsCommandMode = false;
    return true;
}
