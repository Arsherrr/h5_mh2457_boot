static const DSIPacketStruct ReadSequence[] = {
    MakeDSIPacketRead(2, 0xF4),

    MakeDSIPacketEnd(),
};

#define ST7102_DISPLAY_ID 0x71020000

bool ST7102Constractor(DisplayStruct* display) {
    DisplayStartupSequence(display, true, true, 20, 20, 120);

    uint32_t displayID = DisplayDSIReadID(display, ReadSequence);
    if (displayID != ST7102_DISPLAY_ID)
        return false;

    display->ID = displayID;

    display->PixelClock = ST7102_PIXEL_CLOCK;

    display->HorizontalSyncActive = ST7102_HSA;
    display->HorizontalBackPorch  = ST7102_HBP;
    display->HorizontalActive     = ST7102_HACT;
    display->HorizontalFrontPorch = ST7102_HFP;

    display->VerticalSyncActive = ST7102_VSA;
    display->VerticalBackPorch  = ST7102_VBP;
    display->VerticalActive     = ST7102_VACT;
    display->VerticalFrontPorch = ST7102_VFP;

    // DSI Config
    display->ConfigPackets = ST7102Configs;

    display->Color = DisplayColorRGB565;

    DSIStruct* dsi   = display->DSIHandle;
    dsi->LaneClock   = ST7102_LANE_CLOCK;
    dsi->Lanes       = DSILanes2;
    dsi->ColorCoding = DSIColorCoding16C1;

    dsi->IsCommandMode = false;
    return true;
}
