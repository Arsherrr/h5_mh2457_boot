static const DSIPacketStruct ReadSequence[] = {
    MakeDSIPacketRead(1, DCSGetPowerMode),
    MakeDSIPacketRead(1, DCSGetPixelFormat),

    MakeDSIPacketEnd(),
};

#define ST77922_DISPLAY_ID 0x88030000

bool ST77922Constractor(DisplayStruct* display) {
    DisplayStartupSequence(display, true, true, 20, 20, 120);

    uint32_t displayID = DisplayDSIReadID(display, ReadSequence);
    if (display->ID != 0xFFFFFF00 || displayID != ST77922_DISPLAY_ID)
        return false;

    display->ID = displayID;

    display->PixelClock = ST77922_PIXEL_CLOCK;

    display->HorizontalSyncActive = ST77922_HSA;
    display->HorizontalBackPorch  = ST77922_HBP;
    display->HorizontalActive     = ST77922_HACT;
    display->HorizontalFrontPorch = ST77922_HFP;

    display->VerticalSyncActive = ST77922_VSA;
    display->VerticalBackPorch  = ST77922_VBP;
    display->VerticalActive     = ST77922_VACT;
    display->VerticalFrontPorch = ST77922_VFP;

    // DSI Config
    display->ConfigPackets = ST77922Configs;

    display->Color = DisplayColorRGB565;

    DSIStruct* dsi   = display->DSIHandle;
    dsi->LaneClock   = ST77922_LANE_CLOCK;
    dsi->Lanes       = DSILanes1;
    dsi->ColorCoding = DSIColorCoding16C1;

    dsi->IsCommandMode = false;
    return true;
}
