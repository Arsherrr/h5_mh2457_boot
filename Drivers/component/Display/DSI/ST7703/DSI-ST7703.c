#define ST7703_DISPLAY_ID 0x38211F00

bool ST7703Constractor(DisplayStruct* display) {
    if (display->ID && display->ID != ST7703_DISPLAY_ID)
        return false;

    DisplayStartupSequence(display, true, true, 20, 20, 120);

    if (!display->ID && (display->ID = DisplayDSIReadID(display, NULL)) != ST7703_DISPLAY_ID)
        return false;

    display->HorizontalSyncActive = ST7703_HSA;
    display->HorizontalBackPorch  = ST7703_HBP;
    display->HorizontalActive     = ST7703_HACT;
    display->HorizontalFrontPorch = ST7703_HFP;

    display->VerticalSyncActive = ST7703_VSA;
    display->VerticalBackPorch  = ST7703_VBP;
    display->VerticalActive     = ST7703_VACT;
    display->VerticalFrontPorch = ST7703_VFP;

    display->PixelClock = ST7703_PIXEL_CLOCK;

    // DSI Config
    display->ConfigPackets = ST7703Configs;
    display->Color         = DisplayColorRGB565;

    DSIStruct* dsi     = display->DSIHandle;
    dsi->LaneClock     = ST7703_LANE_CLOCK;
    dsi->Lanes         = DSILanes2;
    dsi->ColorCoding   = DSIColorCoding16C1;
    dsi->IsCommandMode = false;
    return true;
}
