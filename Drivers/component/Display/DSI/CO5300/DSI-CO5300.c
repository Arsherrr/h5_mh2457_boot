#define CO5300_DISPLAY_ID 0x33110000

bool CO5300Constractor(DisplayStruct* display) {
    if (display->ID && display->ID != CO5300_DISPLAY_ID)
        return false;

    DisplayStartupSequence(display, true, true, 20, 20, 120);

    if (!display->ID && (display->ID = DisplayDSIReadID(display, NULL)) != CO5300_DISPLAY_ID)
        return false;

    display->HorizontalSyncActive = CO5300_HSA;
    display->HorizontalBackPorch  = CO5300_HBP;
    display->HorizontalActive     = CO5300_HACT;
    display->HorizontalFrontPorch = CO5300_HFP;

    display->VerticalSyncActive = CO5300_VSA;
    display->VerticalBackPorch  = CO5300_VBP;
    display->VerticalActive     = CO5300_VACT;
    display->VerticalFrontPorch = CO5300_VFP;

    display->PixelClock = CO5300_PIXEL_CLOCK;

    // DSI Config
    display->ConfigPackets = CO5300Configs;
    display->Color         = DisplayColorRGB565;

    DSIStruct* dsi = display->DSIHandle;
    dsi->LaneClock = CO5300_LANE_CLOCK;
    dsi->Lanes     = DSILanes1;

    dsi->ColorCoding   = DSIColorCoding16C1;
    dsi->IsCommandMode = false;
    return true;
}
