#define HX8394_DISPLAY_ID 0x83940F00

bool HX8394FConstractor(DisplayStruct* display) {
    if (display->ID && display->ID != HX8394_DISPLAY_ID)
        return false;

    DisplayStartupSequence(display, true, true, 20, 20, 120);

    if (!display->ID && (display->ID = DisplayDSIReadID(display, NULL)) != HX8394_DISPLAY_ID)
        return false;

    display->HorizontalSyncActive = HX8394F_HSA;
    display->HorizontalBackPorch  = HX8394F_HBP;
    display->HorizontalActive     = HX8394F_HACT;
    display->HorizontalFrontPorch = HX8394F_HFP;

    display->VerticalSyncActive = HX8394F_VSA;
    display->VerticalBackPorch  = HX8394F_VBP;
    display->VerticalActive     = HX8394F_VACT;
    display->VerticalFrontPorch = HX8394F_VFP;

    display->PixelClock = HX8394F_PIXEL_CLOCK;

    // DSI Config
    display->ConfigPackets = HX8394FConfigs;
    display->Color         = DisplayColorRGB565;

    DSIStruct* dsi   = display->DSIHandle;
    dsi->LaneClock   = HX8394F_LANE_CLOCK;
    dsi->Lanes       = DSILanes2;
    dsi->ColorCoding = DSIColorCoding16C1;

    dsi->IsCommandMode = false;

    return true;
}